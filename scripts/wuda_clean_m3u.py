#!/usr/bin/env python3
"""生成 wudaliansai 的「只含活流」过滤播放列表。

背景（2026-10-29）：
  容器 iptvtop/wudaliansai 本身正常（/health 有数据、/play 全部 302），但上游后台
  只给"正在打"的比赛配真实流：
    - 完场 / 未开赛 的条目 → 302 到 jsdelivr 占位视频（36 秒黑屏片）
    - 已结束或没源的线路仍挂着「高清 / 赛场原声」标签 → CDN 直返 404
  实测某时刻 211 条里只有约 11 条真能播，用户观感就是"一个都播不了"。

本脚本：
  1. 读容器自己的 live.m3u（127.0.0.1:18765，不过 nginx/CF）
  2. 丢掉 完场 / 未开赛（占位视频）条目
  3. 对去重后的 /play/<hash> 逐个解析 302 目标，再立刻 GET 目标 m3u8：
     200 且含 #EXTM3U → 判活；jsdelivr 占位 → 丢；其余（404/超时）→ 丢
  4. 只输出判活的条目，仍然用 /play/<hash> 链接（容器会重新签 auth_key，
     比直接写 CDN 直链稳定），写到 /srv/tvlive/wuda_clean.m3u

用法：python3 scripts/wuda_clean_m3u.py [--dry-run]
"""
from __future__ import annotations

import argparse
import re
import sys
import time
import urllib.error
import urllib.request

SRC = "http://127.0.0.1:18765/live.m3u"
PUBLIC_BASE = "https://tvlive.shincyann.com/wuda/play/"
OUT = "/srv/tvlive/wuda_clean.m3u"
UA = {"User-Agent": "Mozilla/5.0"}

SKIP_STATUS = ("完场", "未开赛")
PLACEHOLDER_HOST = "jsdelivr"

TIMEOUT = 12
SPACING = 0.15  # 串行间隔，避免打爆上游 CDN


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


_opener = urllib.request.build_opener(NoRedirect)


def fetch(url: str, limit: int | None = None) -> tuple[int | None, bytes]:
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=TIMEOUT) as r:
            return r.status, r.read(limit) if limit else r.read()
    except urllib.error.HTTPError as e:
        return e.code, b""
    except Exception:
        return None, b""


def resolve(play_url: str) -> str:
    """解析 /play/<hash> 的 302 目标（不跟随）。"""
    try:
        with _opener.open(urllib.request.Request(play_url, headers=UA), timeout=TIMEOUT) as r:
            return r.headers.get("Location", "") or ""
    except urllib.error.HTTPError as e:
        if e.code in (301, 302, 303, 307, 308):
            return e.headers.get("Location", "") or ""
        return ""
    except Exception:
        return ""


def is_alive(cdn_url: str) -> bool:
    if not cdn_url or PLACEHOLDER_HOST in cdn_url:
        return False
    code, body = fetch(cdn_url, limit=400)
    return code == 200 and b"#EXTM3U" in body


def parse_playlist(text: str) -> list[dict]:
    lines = [l.strip() for l in text.splitlines()]
    out = []
    for i, line in enumerate(lines):
        if not line.startswith("#EXTINF"):
            continue
        url = ""
        for j in range(i + 1, min(i + 4, len(lines))):
            if lines[j] and not lines[j].startswith("#"):
                url = lines[j]
                break
        if not url.startswith("http"):
            continue
        group = re.search(r'group-title="([^"]*)"', line)
        logo = re.search(r'tvg-logo="([^"]*)"', line)
        out.append({
            "raw_extinf": line,
            "name": line.split(",", 1)[1] if "," in line else "",
            "group": group.group(1) if group else "其他",
            "logo": logo.group(1) if logo else "",
            "play": url,
        })
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    code, body = fetch(SRC)
    if code != 200 or b"#EXTM3U" not in body:
        print(f"ERROR: 容器 live.m3u 拉取失败 http={code}", file=sys.stderr)
        return 1

    entries = parse_playlist(body.decode("utf-8", "replace"))
    candidates = [e for e in entries if not any(s in e["name"] for s in SKIP_STATUS)]
    skipped_placeholder = len(entries) - len(candidates)

    # 去重 play URL，逐个判活
    verdict: dict[str, bool] = {}
    for i, url in enumerate({e["play"] for e in candidates}):
        cdn = resolve(url)
        verdict[url] = is_alive(cdn)
        time.sleep(SPACING)

    alive = [e for e in candidates if verdict.get(e["play"])]
    dead = len(candidates) - len(alive)

    header = [
        "#EXTM3U",
        f"# generated by wuda_clean_m3u.py at {time.strftime('%Y-%m-%d %H:%M:%S')}",
        f"# source entries={len(entries)} placeholder_dropped={skipped_placeholder} "
        f"checked={len(verdict)} alive={len(alive)} dead_dropped={dead}",
    ]
    lines = list(header)
    for e in alive:
        hash_ = e["play"].rstrip("/").rsplit("/", 1)[-1]
        lines.append(e["raw_extinf"])
        lines.append(PUBLIC_BASE + hash_)

    content = "\n".join(lines) + "\n"
    if args.dry_run:
        print(content[:2000])
    else:
        tmp = OUT + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(content)
        import os
        os.replace(tmp, OUT)
        os.chmod(OUT, 0o664)

    print(
        f"entries={len(entries)} placeholder={skipped_placeholder} "
        f"checked={len(verdict)} alive={len(alive)} dead={dead} -> {OUT}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
